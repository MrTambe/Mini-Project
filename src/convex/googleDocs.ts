/**
 * Google Docs integration for Eventure.
 *
 * Creates Google Docs documents for:
 *   - Event reports (summary of registrations, attendance, check-ins)
 *   • Certificates (exportable per-user or per-event)
 *   • Announcements (admin broadcasts formatted as docs)
 *
 * Model: A shared Google Drive folder (owned by the service account or the
 * app owner) is used to store generated docs. The service account creates
 * files inside that folder and returns shareable links.
 *
 * Env vars required on the Convex deployment:
 *   GOOGLE_SERVICE_ACCOUNT_EMAIL  e.g. docs-integration@project.iam.gserviceaccount.com
 *   GOOGLE_SERVICE_ACCOUNT_KEY    the private key (with real newlines)
 *   GOOGLE_DOCS_FOLDER_ID         Drive folder ID where docs are created
 */

function getGoogleAuth() {
  const email = process.env.GOOGLE_SERVICE_ACCOUNT_EMAIL;
  let key = process.env.GOOGLE_SERVICE_ACCOUNT_KEY;
  const folderId = process.env.GOOGLE_DOCS_FOLDER_ID;
  if (!email || !key || !folderId) return null;
  // Handle keys pasted with literal \n sequences
  key = key.replace(/\\n/g, "\n");
  return {
    auth: new google.auth.JWT({
      email,
      key,
      scopes: [
        "https://www.googleapis.com/auth/documents",
        "https://www.googleapis.com/auth/drive",
        "https://www.googleapis.com/auth/drive.file",
      ],
    }),
    folderId,
  };
}

/** Escape text for safe insertion into Google Docs. */
function escapeDocText(text: string): string {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** Build a nicely formatted event report document body (Google Docs API requests). */
function buildEventReportRequests(event: any, stats: any): any[] {
  const requests: any[] = [];

  requests.push({
    insertText: {
      location: { index: 1 },
      text: `Eventure Event Report\n`,
    },
  });

  requests.push({
    updateTextStyle: {
      range: { startIndex: 1, endIndex: 1 + `Eventure Event Report\n`.length },
      textStyle: { bold: true, fontSize: 20 },
    },
  });

  const details = [
    [`Event Name:`, event.name || "Untitled Event"],
    [`Venue:`, event.venue || "Not specified"],
    [`Event Type:`, event.eventType || "individual"],
    [`Status:`, event.status || "active"],
    [`Start Date:`, new Date(event.startDate).toLocaleString("en-IN")],
    [`End Date:`, new Date(event.endDate).toLocaleString("en-IN")],
    [`Max Participants:`, String(event.maxParticipants ?? "Unlimited")],
    [`Description:`, (event.description || "No description").slice(0, 500)],
    ["", ""],
    ["Statistics:", ""],
    [`Total Registrations:`, String(stats.totalRegistrations ?? 0)],
    [`Attended:`, String(stats.attended ?? 0)],
    [`Attendance Rate:`, String(stats.attendanceRate ?? "0%")],
    ["", ""],
    ["Generated by Eventure on:", new Date().toLocaleString("en-IN")],
  ];

  let index = 1 + `Eventure Event Report\n`.length;

  for (const [label, value] of details) {
    const line = `${label} ${value}\n`;
    requests.push({
      insertText: {
        location: { index },
        text: line,
      },
    });
    if (label && !value) {
      // Section header styling
      requests.push({
        updateTextStyle: {
          range: { startIndex: index, endIndex: index + label.length },
          textStyle: { bold: true, fontSize: 14 },
        },
      });
    } else if (label) {
      requests.push({
        updateTextStyle: {
          range: { startIndex: index, endIndex: index + label.length },
          textStyle: { bold: true },
        },
      });
    }
    index += line.length;
  }

  return requests;
}

/** Build a certificate document body. */
function buildCertificateRequests(user: any, event: any, certificateNumber: string): any[] {
  const requests: any[] = [];

  requests.push({
    insertText: {
      location: { index: 1 },
      text: `CERTIFICATE OF PARTICIPATION\n`,
    },
  });

  requests.push({
    updateTextStyle: {
      range: { startIndex: 1, endIndex: 1 + `CERTIFICATE OF PARTICIPATION\n`.length },
      textStyle: { bold: true, fontSize: 24 },
    },
  });

  const lines = [
    "",
    `This is to certify that`,
    "",
    `${user.name || "Participant"}`,
    "",
    `has successfully participated in`,
    "",
    `${event.name || "An Event"}`,
    "",
    `held at ${event.venue || "the venue"} on ${new Date(event.startDate).toLocaleDateString("en-IN")}.`,
    "",
    `Certificate Number: ${certificateNumber}`,
    `Issued on: ${new Date().toLocaleDateString("en-IN")}`,
    "",
    "Eventure — One app. Every event. Zero hassle.",
  ];

  let index = 1 + `CERTIFICATE OF PARTICIPATION\n`.length;

  for (const line of lines) {
    const text = `${line}\n`;
    requests.push({
      insertText: {
        location: { index },
        text,
      },
    });
    if (line === `Certificate Number: ${certificateNumber}` || line.startsWith(`Certificate Number:`)) {
      requests.push({
        updateTextStyle: {
          range: { startIndex: index, endIndex: index + text.length },
          textStyle: { bold: true },
        },
      });
    }
    if (line.startsWith("has successfully participated")) {
      requests.push({
        updateTextStyle: {
          range: { startIndex: index, endIndex: index + text.length },
          textStyle: { italic: true },
        },
      });
    }
    index += text.length;
  }

  return requests;
}

/** Create a Google Doc inside the configured folder. */
async function createGoogleDoc(docs: any, drive: any, folderId: string, title: string, requests: any[]) {
  // Create the document
  const created = await docs.documents.create({
    requestBody: { title },
  });
  const documentId = created.data.documentId;

  // Apply content requests
  if (requests.length > 0) {
    await docs.documents.batchUpdate({
      documentId,
      requestBody: { requests },
    });
  }

  // Move the file into the configured folder (files are created in root by default)
  await drive.files.update({
    fileId: documentId,
    addParents: folderId,
    fields: "id, parents",
  });

  // Make it viewable by anyone with the link (optional - can be restricted)
  try {
    await drive.permissions.create({
      fileId: documentId,
      requestBody: { role: "reader", type: "anyone" },
      fields: "id",
    });
  } catch {
    // Permission may already be set or domain-restricted; non-fatal
  }

  const file = await drive.files.get({
    fileId: documentId,
    fields: "id, name, webViewLink, webContentLink",
  });

  return {
    documentId,
    title: file.data.name,
    url: file.data.webViewLink,
    exportUrl: file.data.webContentLink,
  };
}

/**
 * Internal action: generate an event report Google Doc.
 * Called from Convex actions that have access to internal queries.
 */
export const createEventReportDoc = internalAction({
  args: { eventId: v.id("events") },
  handler: async (ctx, args) => {
    const g = getGoogleAuth();
    if (!g) {
      return {
        success: false,
        message:
          "Google Docs not configured: missing GOOGLE_SERVICE_ACCOUNT_EMAIL / GOOGLE_SERVICE_ACCOUNT_KEY / GOOGLE_DOCS_FOLDER_ID.",
      };
    }

    const event: any = await ctx.runQuery(internal.sheetsData.getEventInternal, {
      eventId: args.eventId,
    });
    if (!event) {
      return { success: false, message: "Event not found" };
    }

    const registrations: any[] = await ctx.runQuery(internal.sheetsData.getRegistrationsInternal, {
      eventId: args.eventId,
    });

    const totalRegistrations = registrations.length;
    const attended = registrations.filter((r) => r.status === "attended").length;
    const attendanceRate = totalRegistrations
      ? `${Math.round((attended / totalRegistrations) * 100)}%`
      : "0%";

    const stats = {
      totalRegistrations,
      attended,
      attendanceRate,
    };

    const docs = google.docs({ version: "v1", auth: g.auth });
    const drive = google.drive({ version: "v3", auth: g.auth });

    const requests = buildEventReportRequests(event, stats);
    const result = await createGoogleDoc(
      docs,
      drive,
      g.folderId,
      `Eventure Report — ${event.name}`,
      requests
    );

    return {
      success: true,
      document: result,
      message: `Event report created for "${event.name}"`,
    };
  },
});

/**
 * Internal action: generate a participation certificate Google Doc.
 */
export const createCertificateDoc = internalAction({
  args: {
    eventId: v.id("events"),
    userId: v.id("users"),
    certificateNumber: v.string(),
  },
  handler: async (ctx, args) => {
    const g = getGoogleAuth();
    if (!g) {
      return {
        success: false,
        message:
          "Google Docs not configured: missing GOOGLE_SERVICE_ACCOUNT_EMAIL / GOOGLE_SERVICE_ACCOUNT_KEY / GOOGLE_DOCS_FOLDER_ID.",
      };
    }

    const event: any = await ctx.runQuery(internal.sheetsData.getEventInternal, {
      eventId: args.eventId,
    });
    if (!event) {
      return { success: false, message: "Event not found" };
    }

    const user: any = await ctx.runQuery(internal.sheetsData.getUserByIdInternal, {
      userId: args.userId,
    });
    if (!user) {
      return { success: false, message: "User not found" };
    }

    const docs = google.docs({ version: "v1", auth: g.auth });
    const drive = google.drive({ version: "v3", auth: g.auth });

    const requests = buildCertificateRequests(user, event, args.certificateNumber);
    const result = await createGoogleDoc(
      docs,
      drive,
      g.folderId,
      `Certificate — ${user.name || "Participant"} — ${event.name}`,
      requests
    );

    return {
      success: true,
      document: result,
      message: `Certificate created for "${user.name}"`,
    };
  },
});

/**
 * Public action: list previously generated docs is not stored in DB by default.
 * This is a helper to check configuration status.
 */
export const checkGoogleDocsConfig = action({
  args: {},
  handler: async () => {
    const configured = !!(
      process.env.GOOGLE_SERVICE_ACCOUNT_EMAIL &&
      process.env.GOOGLE_SERVICE_ACCOUNT_KEY &&
      process.env.GOOGLE_DOCS_FOLDER_ID
    );
    return {
      configured,
      message: configured
        ? "Google Docs integration is configured."
        : "Google Docs is not configured. Set GOOGLE_SERVICE_ACCOUNT_EMAIL, GOOGLE_SERVICE_ACCOUNT_KEY, and GOOGLE_DOCS_FOLDER_ID on the Convex deployment.",
    };
  },
});
